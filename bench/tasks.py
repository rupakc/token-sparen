"""SWE-bench task pool, per-repository streams and the seeded pool extension.

`bench/data/pool.jsonl` (committed; regenerated by `bench/data/fetch_pool.py`) holds a header
(dataset revisions, fetch date, Mini tasks without an arm64 image) and one row per SWE-bench
Verified task that has a prebuilt arm64 evaluation image, flagged ``mini`` for the Verified Mini
subset. It holds no problem statement or patch: those are fetched at prepare time into the bench
workspace (`dataset.jsonl`, pinned revision, sha256 in `dataset.meta.json`) and read back by
`load_dataset_rows`, which re-checks the hash.

A learner arm runs the tasks of one repository as a stream in commit order (`streams`), so state
built on earlier tasks can only help later ones the way it would for a user working forward in
time. `extend` draws further tasks for a larger confirmation, seeded and stratified by
repository, Mini repositories first; the draw is a pure function of the pool and the seed, so the
set is declared before any result is seen.
"""

from __future__ import annotations

import hashlib
import json
import os
import random
import subprocess
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

BENCH_DIR = Path(__file__).resolve().parent
POOL_FILE = BENCH_DIR / "data" / "pool.jsonl"
FAKE_DIR = BENCH_DIR / "fixtures" / "fake"
DATASET_FILE = "dataset.jsonl"
DATASET_META_FILE = "dataset.meta.json"
HEADER_KEYS = ("verified_revision", "mini_revision", "fetched")
ROW_KEYS = ("instance_id", "repo", "base_commit", "created_at", "image", "mini")

# The fake task: a tiny repository built from `bench/fixtures/fake/` with a fixed author, date
# and file bytes, so its commit id is the same on every machine (checked by the tests).
FAKE_REPO_FILES = ("calc.py", "test_calc.py")
FAKE_BASE_COMMIT = "7c85f5f733d709fe08da46729410f907586f2a07"
FAKE_IMAGE = "tsb-fake:local"
_FAKE_GIT_ENV = {
    "GIT_AUTHOR_NAME": "bench",
    "GIT_AUTHOR_EMAIL": "bench@example.invalid",
    "GIT_AUTHOR_DATE": "2020-01-01T00:00:00+00:00",
    "GIT_COMMITTER_NAME": "bench",
    "GIT_COMMITTER_EMAIL": "bench@example.invalid",
    "GIT_COMMITTER_DATE": "2020-01-01T00:00:00+00:00",
}
_GIT_REDIRECTS = ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_OBJECT_DIRECTORY")


class PoolError(ValueError):
    """The pool file or the prepared dataset is malformed or does not match its record."""


@dataclass(frozen=True)
class Task:
    instance_id: str
    repo: str
    base_commit: str
    created_at: str
    image: str
    mini: bool


def arm64_image(instance_id: str) -> str:
    """The prebuilt arm64 SWE-bench evaluation image of a task (Docker Hub naming)."""
    return "swebench/sweb.eval.arm64." + instance_id.replace("__", "_1776_") + ":latest"


def _pool_lines(path: Path) -> list[dict[str, Any]]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise PoolError(f"pool unreadable: {exc}") from exc
    try:
        return [json.loads(line) for line in lines if line.strip()]
    except json.JSONDecodeError as exc:
        raise PoolError(f"pool line not JSON: {exc}") from exc


def read_pool_header(path: Path = POOL_FILE) -> dict[str, Any]:
    lines = _pool_lines(path)
    if not lines or not all(isinstance(lines[0].get(k), str) for k in HEADER_KEYS):
        raise PoolError(f"pool header must hold {', '.join(HEADER_KEYS)}")
    return lines[0]


def _task(row: Mapping[str, Any]) -> Task:
    missing = [k for k in ROW_KEYS if k not in row]
    if missing:
        raise PoolError(f"pool row lacks {', '.join(missing)}")
    if not isinstance(row["mini"], bool):
        raise PoolError(f"{row['instance_id']}: mini must be a boolean")
    task = Task(**{k: row[k] for k in ROW_KEYS})
    if task.image != arm64_image(task.instance_id):
        raise PoolError(f"{task.instance_id}: image {task.image!r} is not its arm64 image")
    return task


def load_pool(path: Path = POOL_FILE) -> list[Task]:
    read_pool_header(path)
    tasks = [_task(row) for row in _pool_lines(path)[1:]]
    ids = [t.instance_id for t in tasks]
    if len(set(ids)) != len(ids):
        raise PoolError("duplicate instance_id in pool")
    return tasks


def streams(tasks: Sequence[Task]) -> dict[str, list[Task]]:
    """Repository → its tasks in commit order (``created_at``, then ``instance_id``)."""
    out: dict[str, list[Task]] = {}
    for task in tasks:
        out.setdefault(task.repo, []).append(task)
    return {
        repo: sorted(group, key=lambda t: (t.created_at, t.instance_id))
        for repo, group in sorted(out.items())
    }


def extend(pool: Sequence[Task], have: Sequence[Task], n: int, *, seed: int) -> list[Task]:
    """``n`` further tasks of ``pool`` not in ``have``: seeded, stratified by repository.

    Repositories of the Mini subset come first (their own pool tasks before any other
    repository's); within a tier the draw alternates between repositories in name order, each
    repository's candidates shuffled by its own seeded generator, so adding a repository to the
    pool never reorders another repository's draw. Fewer than ``n`` are returned only when the
    pool is exhausted. Deterministic for a given pool, ``have`` and ``seed``.
    """
    if n < 0:
        raise ValueError("n must be >= 0")
    taken = {t.instance_id for t in have}
    candidates = streams([t for t in pool if t.instance_id not in taken])
    mini_repos = {t.repo for t in pool if t.mini}
    order: dict[str, list[Task]] = {}
    for repo, group in candidates.items():
        shuffled = sorted(group, key=lambda t: t.instance_id)
        random.Random(f"{seed}:{repo}").shuffle(shuffled)
        order[repo] = shuffled
    drawn: list[Task] = []
    for tier in (
        sorted(r for r in order if r in mini_repos),
        sorted(r for r in order if r not in mini_repos),
    ):
        queues = [list(order[r]) for r in tier]
        while len(drawn) < n and any(queues):
            for queue in queues:
                if queue and len(drawn) < n:
                    drawn.append(queue.pop(0))
    return drawn


def write_dataset_rows(workspace: Path, rows: Sequence[Mapping[str, Any]], revision: str) -> Path:
    """Write ``dataset.jsonl`` (0600) and its record (revision, sha256, ids) in ``workspace``."""
    data = "".join(json.dumps(r, sort_keys=True) + "\n" for r in rows).encode("utf-8")
    meta = {
        "dataset": "SWE-bench/SWE-bench_Verified",
        "revision": revision,
        "sha256": hashlib.sha256(data).hexdigest(),
        "rows": len(rows),
    }
    target = workspace / DATASET_FILE
    _write_private(target, data)
    _write_private(workspace / DATASET_META_FILE, (json.dumps(meta, indent=2) + "\n").encode())
    return target


def _write_private(path: Path, data: bytes) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(data)
    if os.name == "posix":
        os.chmod(path, 0o600)


def load_dataset_rows(workspace: Path) -> dict[str, dict[str, Any]]:
    """instance_id → dataset row (problem statement, gold patch, …) prepared in ``workspace``.

    Refused (`PoolError`) when the file's sha256 or row count differs from its record, or the
    recorded revision differs from the pool header's Verified revision.
    """
    try:
        meta = json.loads((workspace / DATASET_META_FILE).read_text(encoding="utf-8"))
        data = (workspace / DATASET_FILE).read_bytes()
    except (OSError, json.JSONDecodeError) as exc:
        raise PoolError(f"dataset not prepared in the workspace: {exc}") from exc
    if hashlib.sha256(data).hexdigest() != meta.get("sha256"):
        raise PoolError("dataset.jsonl does not match its recorded sha256")
    if meta.get("revision") != read_pool_header()["verified_revision"]:
        raise PoolError("dataset revision differs from the pool's Verified revision")
    rows = [json.loads(line) for line in data.decode("utf-8").splitlines() if line.strip()]
    if len(rows) != meta.get("rows"):
        raise PoolError("dataset.jsonl row count differs from its record")
    return {str(r["instance_id"]): r for r in rows}


def _fake_tasks() -> tuple[Task, ...]:
    tasks = []
    for repo, day in (("fake/alpha", 1), ("fake/beta", 3)):
        for k in (1, 2):
            iid = repo.replace("/", "__") + f"-{k}"
            created = f"2020-01-{day + k:02d}T00:00:00Z"
            tasks.append(Task(iid, repo, FAKE_BASE_COMMIT, created, FAKE_IMAGE, mini=False))
    return tuple(tasks)


FAKE_TASKS: tuple[Task, ...] = _fake_tasks()


def make_fake_repo(dest: Path) -> str:
    """Create the fake task repository at ``dest`` (new directory); return its commit id."""
    dest.mkdir(parents=True)
    for name in FAKE_REPO_FILES:
        (dest / name).write_bytes((FAKE_DIR / name).read_bytes().replace(b"\r\n", b"\n"))
    env = {k: v for k, v in os.environ.items() if k not in _GIT_REDIRECTS} | _FAKE_GIT_ENV
    git = ["git", "-c", "init.defaultBranch=main", "-c", "commit.gpgSign=false"]
    git += ["-c", "core.autocrlf=false", "-C", str(dest)]
    for args in (["init", "-q"], ["add", *FAKE_REPO_FILES], ["commit", "-q", "-m", "fake task"]):
        subprocess.run([*git, *args], check=True, capture_output=True, env=env)  # noqa: S603
    out = subprocess.run(  # noqa: S603
        [*git, "rev-parse", "HEAD"], check=True, capture_output=True, text=True, env=env
    )
    return out.stdout.strip()
